import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { normalizeSessionPreferences, createSessionStore, DEFAULT_SESSION_PREFERENCES } from '@/vela/sessions/sessionStore';
import { SESSION_STYLES, computeSessionSpans } from '@/vela/sessions/sessionMath';
assert.equal(normalizeSessionPreferences({ bandOpacity: -5 }).bandOpacity, 0);
assert.equal(normalizeSessionPreferences({ bandOpacity: 150 }).bandOpacity, 100);
assert.equal(normalizeSessionPreferences({ bandOpacity: NaN }).bandOpacity, DEFAULT_SESSION_PREFERENCES.bandOpacity);
assert.equal(normalizeSessionPreferences({ bandOpacity: 33.4 }).bandOpacity, 33);
const values = new Map<string, string>();
const store = createSessionStore({ getItem: k => values.get(k) ?? null, setItem: (k, v) => values.set(k, v) });
store.patch({ bandOpacity: 42 });
assert.equal(store.getSnapshot().preferences.bandOpacity, 42);
assert.equal(JSON.parse(values.get('pulsedesk.sessions.v1')!).bandOpacity, 42);
store.reset(); assert.equal(store.getSnapshot().preferences.bandOpacity, DEFAULT_SESSION_PREFERENCES.bandOpacity);
const day = Date.parse('2026-01-15T00:00:00Z');
const spans = computeSessionSpans(day, day + 86400000, { mode: 'macro', enabledSessions: { asia: true, london: true, ny: true }, showOverlap: true });
assert.equal(SESSION_STYLES.asia.name, '亚太交易时段');
assert.equal(SESSION_STYLES.london.name, '伦敦交易时段');
assert.equal(SESSION_STYLES.ny.name, '纽约交易时段');
assert.ok(spans.every(s => s.badgeLabel.startsWith(s.name) && s.badgeLabel.includes('–')));
assert.equal(spans.find(s => s.id === 'asia')!.badgeLabel, '亚太交易时段 00:00–08:00');
// The audit sidebar is retired entirely, including its old persisted-layout id.
assert.equal(existsSync('src/vela/priceAction/registerPriceActionPanel.tsx'), false);
assert.equal(existsSync('src/vela/priceAction/PriceActionPanel.tsx'), false);
const terminal = readFileSync('src/vela/VelaTerminal.tsx', 'utf8');
assert.ok(terminal.includes("unregisterSidePanel('pulsedesk-price-action')"));
assert.ok(terminal.includes("unregisterWidgetAction('pd-price-action')"));
assert.ok(!terminal.includes('registerPriceActionPanel'));
const layer = readFileSync('src/vela/sessions/sessionLayer.ts', 'utf8');
assert.ok(layer.includes('prefs.bandOpacity / 100'));
assert.ok(layer.includes('亚太交易时段高点'));
assert.ok(layer.includes('亚太交易时段低点'));
assert.ok(!layer.includes('`AH '));
assert.ok(!layer.includes('`AL '));
console.log('session-ui: opacity persistence, complete Chinese labels and retired audit panel passed');
